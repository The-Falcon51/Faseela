#!/usr/bin/env node
// Generates public/i18n-de.js from src/i18n/de.json. The German dictionary is loaded lazily by
// setLanguage('de') (public/app.js), so Arabic/English visitors never download it.
// The output is a plain script (CSP: script-src 'self') that only assigns one frozen global.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'src/i18n/de.json');
const target = path.join(root, 'public/i18n-de.js');

function build() {
  const dict = JSON.parse(fs.readFileSync(source, 'utf8'));
  for (const [key, value] of Object.entries(dict)) {
    if (typeof value !== 'string' || value.trim() === '') throw new Error(`i18n de: empty or non-string value for "${key}"`);
  }
  // JSON is valid JS; escape the two line separators JSON allows but older JS engines reject.
  const LS = String.fromCharCode(0x2028);
  const PS = String.fromCharCode(0x2029);
  const body = JSON.stringify(dict).split(LS).join('\\u2028').split(PS).join('\\u2029');
  const out = `// Generated by scripts/build-i18n-de.cjs from src/i18n/de.json. Do not edit by hand.\nwindow.FASEELA_I18N_DE = Object.freeze(${body});\n`;
  fs.writeFileSync(target, out);
  return Object.keys(dict).length;
}

if (require.main === module) {
  const count = build();
  process.stdout.write(`i18n-de.js written (${count} keys)\n`);
}
module.exports = { build };
