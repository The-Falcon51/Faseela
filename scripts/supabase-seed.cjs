#!/usr/bin/env node
// Generates supabase/seed.sql from database/seed_data.json, reusing the canonical
// tree builder (functions/domain.js buildTreeRecords: 4 shares/tree, minor units).
// Usage: node scripts/supabase-seed.cjs  -> writes supabase/seed.sql (idempotent upsert).
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { buildTreeRecords } = require('../functions/domain.js');

const root = path.resolve(__dirname, '..');
const seed = JSON.parse(fs.readFileSync(path.join(root, 'database/seed_data.json'), 'utf8'));
const trees = Array.isArray(seed.trees) ? seed.trees : [];
if (!trees.length) throw new Error('seed_data.json contains no trees.');

const rows = trees.map((seedTree) => {
  const { tree, publicTree } = buildTreeRecords(seedTree);
  return {
    tree_id: publicTree.treeId,
    status: publicTree.status,
    crop_category: publicTree.cropCategory,
    name: publicTree.name,
    name_en: publicTree.nameEn,
    region: publicTree.region,
    region_en: publicTree.regionEn,
    tree_type: publicTree.treeType,
    tree_type_en: publicTree.treeTypeEn,
    planted_year: publicTree.plantedYear,
    estimated_annual_yield_kg: publicTree.estimatedAnnualYieldKg,
    carbon_offset_kg_year: publicTree.carbonOffsetKgYear,
    images: publicTree.images,
    total_shares: publicTree.totalShares,
    available_shares: publicTree.availableShares,
    price_per_share_minor: publicTree.pricePerShareMinor,
    land_price_minor: publicTree.landPriceMinor,
    has_land_option: publicTree.hasLandOption,
    land_area_sqm: publicTree.landAreaSqm,
    currency: publicTree.currency,
    farm_id: tree.farmId,
    mill_id: tree.millId,
    sold_shares: tree.soldShares,
    land_parcel: tree.landParcel,
    gps: tree.gps
  };
});

// Dollar-quoted JSON literal: no manual escaping of quotes inside the data.
const tag = '$seed$';
const json = JSON.stringify(rows, null, 2);
if (json.includes(tag)) throw new Error('Seed data contains the dollar-quote tag.');

const sql = `-- GENERATED by scripts/supabase-seed.cjs from database/seed_data.json. Do not edit by hand.
-- Idempotent: listing data is upserted; live inventory counters (sold/reserved) are only set on first insert.
with data as (
  select * from jsonb_to_recordset(${tag}${json}${tag}::jsonb) as x(
    tree_id text, status text, crop_category text, name text, name_en text, region text, region_en text,
    tree_type text, tree_type_en text, planted_year integer, estimated_annual_yield_kg numeric,
    carbon_offset_kg_year numeric, images text[], total_shares integer, available_shares integer,
    price_per_share_minor bigint, land_price_minor bigint, has_land_option boolean, land_area_sqm numeric,
    currency text, farm_id text, mill_id text, sold_shares integer, land_parcel jsonb, gps jsonb)
), listing as (
  insert into public.trees_public (tree_id, status, crop_category, name, name_en, region, region_en, tree_type,
    tree_type_en, planted_year, estimated_annual_yield_kg, carbon_offset_kg_year, images, total_shares,
    available_shares, price_per_share_minor, land_price_minor, has_land_option, land_area_sqm, currency)
  select tree_id, status, crop_category, name, name_en, region, region_en, tree_type, tree_type_en, planted_year,
    estimated_annual_yield_kg, carbon_offset_kg_year, images, total_shares, available_shares, price_per_share_minor,
    land_price_minor, has_land_option, land_area_sqm, currency
  from data
  on conflict (tree_id) do update set
    status = excluded.status, crop_category = excluded.crop_category, name = excluded.name, name_en = excluded.name_en,
    region = excluded.region, region_en = excluded.region_en, tree_type = excluded.tree_type,
    tree_type_en = excluded.tree_type_en, planted_year = excluded.planted_year,
    estimated_annual_yield_kg = excluded.estimated_annual_yield_kg, carbon_offset_kg_year = excluded.carbon_offset_kg_year,
    images = excluded.images, price_per_share_minor = excluded.price_per_share_minor,
    land_price_minor = excluded.land_price_minor, has_land_option = excluded.has_land_option,
    land_area_sqm = excluded.land_area_sqm, updated_at = now()
  returning tree_id
)
insert into private.trees (tree_id, farm_id, mill_id, total_shares, sold_shares, reserved_shares,
  price_per_share_minor, land_price_minor, currency, land_parcel, gps)
select d.tree_id, d.farm_id, d.mill_id, d.total_shares, d.sold_shares, 0, d.price_per_share_minor,
  d.land_price_minor, d.currency, d.land_parcel, d.gps
from data d join listing l on l.tree_id = d.tree_id
on conflict (tree_id) do update set
  farm_id = excluded.farm_id, mill_id = excluded.mill_id, price_per_share_minor = excluded.price_per_share_minor,
  land_price_minor = excluded.land_price_minor, land_parcel = excluded.land_parcel, gps = excluded.gps, updated_at = now();

-- Re-derive the public counter from the inventory (keeps listing and inventory consistent).
update public.trees_public p
   set available_shares = t.total_shares - t.sold_shares - t.reserved_shares
  from private.trees t
 where t.tree_id = p.tree_id;
`;

const out = path.join(root, 'supabase/seed.sql');
fs.writeFileSync(out, sql);
console.log(`wrote ${path.relative(root, out)} (${rows.length} trees)`);
