#!/usr/bin/env node
// Builds all self-hosted front-end assets (review F-06/F-10): no third-party script or
// font origins at runtime. Outputs are committed because Hosting + Capacitor serve public/.
//   public/assets/tailwind.css  <- tailwind.config.cjs + src/tailwind.css (content: public/*.html, *.js, *.mjs)
//   public/supabase-client.mjs  <- src/supabase-client.src.mjs bundled with npm `@supabase/supabase-js`
//   public/i18n-de.js          <- src/i18n/de.json (lazily loaded German dictionary)
//   public/vendor/lucide.min.js <- node_modules/lucide (pinned in package.json)
//   public/fonts/*              <- @fontsource-variable/{cairo,plus-jakarta-sans}
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const pub = path.join(root, 'public');
const nm = path.join(root, 'node_modules');
const bin = (name) => path.join(nm, '.bin', name);

function step(label, fn) {
  process.stdout.write(`• ${label} … `);
  fn();
  process.stdout.write('ok\n');
}

step('tailwind css', () => {
  fs.mkdirSync(path.join(pub, 'assets'), { recursive: true });
  execFileSync(bin('tailwindcss'), ['-c', 'tailwind.config.cjs', '-i', 'src/tailwind.css', '-o', 'public/assets/tailwind.css', '--minify'], { cwd: root, stdio: 'pipe' });
});

step('supabase client bundle', () => {
  execFileSync(bin('esbuild'), [
    'src/supabase-client.src.mjs', '--bundle', '--format=esm', '--minify', '--target=es2020',
    '--legal-comments=linked', '--outfile=public/supabase-client.mjs'
  ], { cwd: root, stdio: 'pipe' });
});

step('german dictionary', () => {
  require('./build-i18n-de.cjs').build();
});

step('lucide icons', () => {
  fs.mkdirSync(path.join(pub, 'vendor'), { recursive: true });
  fs.copyFileSync(path.join(nm, 'lucide/dist/umd/lucide.min.js'), path.join(pub, 'vendor/lucide.min.js'));
});

step('self-hosted fonts', () => {
  const fontsDir = path.join(pub, 'fonts');
  fs.mkdirSync(fontsDir, { recursive: true });
  const families = [
    { pkg: '@fontsource-variable/cairo', css: 'wght.css', from: 'Cairo Variable', to: 'Cairo' },
    { pkg: '@fontsource-variable/plus-jakarta-sans', css: 'wght.css', from: 'Plus Jakarta Sans Variable', to: 'Plus Jakarta Sans' }
  ];
  let css = '/* Generated by scripts/build-web.cjs — self-hosted, no Google Fonts requests (DSGVO). */\n';
  for (const f of families) {
    const pkgDir = path.join(nm, f.pkg);
    let source = fs.readFileSync(path.join(pkgDir, f.css), 'utf8');
    for (const file of fs.readdirSync(path.join(pkgDir, 'files'))) {
      if (!/-wght-normal\.woff2$/.test(file) || /(cyrillic|vietnamese|greek)/.test(file)) continue;
      fs.copyFileSync(path.join(pkgDir, 'files', file), path.join(fontsDir, file));
    }
    source = source
      .replaceAll(`'${f.from}'`, `'${f.to}'`)
      .replace(/url\(\.\/files\/([^)]+)\)/g, 'url(./$1)');
    // keep only the subsets we ship
    source = source.split('@font-face').filter((block, i) => i === 0 || !/(cyrillic|vietnamese|greek)/.test(block)).join('@font-face');
    css += source + '\n';
  }
  fs.writeFileSync(path.join(fontsDir, 'fonts.css'), css);
});

// Last: every step above can change a file the build id is computed from.
step('build id in page and service worker', () => {
  require('./version-assets.cjs').run(false);
});

console.log('✅ Front-end assets built.');
